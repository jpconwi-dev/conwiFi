"""Routing, firewall (nftables), DHCP (dnsmasq) and customer authorization.

Customer access control: a kernel nftables set `authorized` holds the MAC of every paid customer
together with a timeout equal to the remaining session time, so access also expires on its own even
if the monitor service is down. The monitor re-syncs the set from SQLite every few seconds."""
import ipaddress
import json
import socket
import subprocess
from pathlib import Path

from .config import paths

TABLE = "jp_pisowifi"
DNSMASQ_CONF = Path("/etc/dnsmasq.d/jp-pisowifi.conf")
NFT_FILE = Path("/etc/jp-pisowifi/jp-pisowifi.nft")


# ---------- interface detection ----------
def detect_interfaces(sys_net="/sys/class/net") -> list[dict]:
    out = []
    base = Path(sys_net)
    if not base.exists():
        return out
    for p in sorted(base.iterdir()):
        if p.name == "lo" or (p / "wireless").exists() or not (p / "device").exists():
            continue
        try:
            if int((p / "type").read_text()) != 1:
                continue
            real = str((p / "device").resolve())
            drv = (p / "device" / "driver")
            out.append({
                "name": p.name,
                "mac": (p / "address").read_text().strip(),
                "usb": "/usb" in real,
                "driver": drv.resolve().name if drv.exists() else "",
                "up": (p / "operstate").read_text().strip(),
            })
        except (OSError, ValueError):
            continue
    return out


def pick_interfaces(ifaces: list[dict]) -> tuple[str | None, str | None, str]:
    """Return (wan, lan, note). Only auto-picks when unambiguous: one built-in + one USB."""
    builtin = [i for i in ifaces if not i["usb"]]
    usb = [i for i in ifaces if i["usb"]]
    if len(builtin) == 1 and len(usb) == 1:
        return builtin[0]["name"], usb[0]["name"], "auto-detected"
    return None, None, f"ambiguous ({len(builtin)} built-in, {len(usb)} USB): select manually"


# ---------- validation ----------
def validate_network(net: dict) -> list[str]:
    errs = []
    try:
        lan = ipaddress.ip_interface(f"{net['lan_ip']}/{net['lan_prefix']}")
        if not (16 <= int(net["lan_prefix"]) <= 29):
            errs.append("LAN prefix must be between /16 and /29.")
        if not lan.ip.is_private:
            errs.append("LAN address must be a private address.")
        s, e = ipaddress.ip_address(net["dhcp_start"]), ipaddress.ip_address(net["dhcp_end"])
        if s not in lan.network or e not in lan.network:
            errs.append("DHCP range must be inside the LAN subnet.")
        if int(s) > int(e):
            errs.append("DHCP start must not be after DHCP end.")
        if s <= lan.ip <= e:
            errs.append("The gateway address must not be inside the DHCP range.")
    except (ValueError, KeyError) as ex:
        errs.append(f"Invalid address: {ex}")
    for d in net.get("dns_servers", []):
        try:
            ipaddress.ip_address(d)
        except ValueError:
            errs.append(f"Invalid DNS server: {d}")
    if net.get("wan_iface") and net.get("wan_iface") == net.get("lan_iface"):
        errs.append("WAN and LAN interfaces must be different.")
    return errs


# ---------- renderers ----------
def render_nft(net: dict) -> str:
    wan, lan, ip = net["wan_iface"], net["lan_iface"], net["lan_ip"]
    return f"""# Generated by JP-PisoWiFi. Do not edit; change settings in the admin panel.
table inet {TABLE}
delete table inet {TABLE}
table inet {TABLE} {{
  set authorized {{
    type ether_addr
    flags timeout
  }}
  chain input {{
    type filter hook input priority 0; policy drop;
    iifname "lo" accept
    ct state established,related accept
    ct state invalid drop
    meta l4proto {{ icmp, ipv6-icmp }} accept
    iifname "{lan}" udp dport {{ 53, 67 }} accept
    iifname "{lan}" tcp dport {{ 53, 80 }} accept
    iifname "{wan}" tcp dport {{ 22, 80 }} accept
    iifname "{wan}" udp dport 68 accept
  }}
  chain forward {{
    type filter hook forward priority 0; policy drop;
    ct state invalid drop
    iifname "{lan}" oifname "{wan}" ether saddr @authorized accept
    iifname "{wan}" oifname "{lan}" ct state established,related accept
    iifname "{lan}" meta l4proto tcp reject with tcp reset
    iifname "{lan}" meta l4proto udp reject
  }}
  chain prerouting {{
    type nat hook prerouting priority dstnat; policy accept;
    iifname "{lan}" ip daddr != {ip} ether saddr != @authorized tcp dport 80 dnat ip to {ip}:80
  }}
  chain postrouting {{
    type nat hook postrouting priority srcnat; policy accept;
    oifname "{wan}" masquerade
  }}
}}
"""


def render_dnsmasq(net: dict) -> str:
    mask = str(ipaddress.ip_network(f"{net['lan_ip']}/{net['lan_prefix']}", strict=False).netmask)
    servers = "\n".join(f"server={d}" for d in net.get("dns_servers", []))
    return f"""# Generated by JP-PisoWiFi
interface={net['lan_iface']}
bind-interfaces
except-interface=lo
dhcp-range={net['dhcp_start']},{net['dhcp_end']},{mask},{net['dhcp_lease']}
dhcp-option=option:router,{net['lan_ip']}
dhcp-option=option:dns-server,{net['lan_ip']}
dhcp-authoritative
no-resolv
{servers}
cache-size=500
"""


# ---------- authorization backends ----------
class SimBackend:
    mode = "simulation"

    def __init__(self, cfg):
        self.file = paths(cfg)["sim_auth"]
        self.file.parent.mkdir(parents=True, exist_ok=True)

    def _load(self) -> dict:
        try:
            return json.loads(self.file.read_text())
        except (OSError, ValueError):
            return {}

    def list_authorized(self) -> dict[str, int]:
        import time
        now = time.time()
        return {m: int(t - now) for m, t in self._load().items() if t > now}

    def authorize(self, mac: str, seconds: int):
        import time
        d = self._load()
        d[mac] = time.time() + seconds
        self.file.write_text(json.dumps(d))

    def revoke(self, mac: str, ip: str | None = None):
        d = self._load()
        d.pop(mac, None)
        self.file.write_text(json.dumps(d))

    def flush(self):
        self.file.write_text("{}")


class NftBackend:
    mode = "nftables"

    def _nft(self, *args, check=False):
        return subprocess.run(["nft", *args], capture_output=True, text=True, check=check)

    def list_authorized(self) -> dict[str, int]:
        r = self._nft("-j", "list", "set", "inet", TABLE, "authorized")
        if r.returncode != 0:
            return {}
        out = {}
        try:
            for item in json.loads(r.stdout).get("nftables", []):
                for el in item.get("set", {}).get("elem", []):
                    if isinstance(el, dict) and "elem" in el:
                        out[el["elem"]["val"].lower()] = int(el["elem"].get("expires", 0))
                    elif isinstance(el, str):
                        out[el.lower()] = 0
        except (ValueError, KeyError):
            pass
        return out

    def authorize(self, mac: str, seconds: int):
        self._nft("delete", "element", "inet", TABLE, "authorized", "{ %s }" % mac)
        r = self._nft("add", "element", "inet", TABLE, "authorized",
                      "{ %s timeout %ds }" % (mac, max(1, seconds)))
        if r.returncode != 0:
            raise RuntimeError(r.stderr.strip())

    def revoke(self, mac: str, ip: str | None = None):
        self._nft("delete", "element", "inet", TABLE, "authorized", "{ %s }" % mac)
        if ip:  # drop existing connections right away
            subprocess.run(["conntrack", "-D", "-s", ip], capture_output=True)

    def flush(self):
        self._nft("flush", "set", "inet", TABLE, "authorized")


def get_backend(cfg):
    return SimBackend(cfg) if cfg["simulation_mode"] else NftBackend()


# ---------- apply / status ----------
def internet_ok(cfg) -> bool:
    if cfg["simulation_mode"]:
        return True
    for host in ("1.1.1.1", "8.8.8.8", "9.9.9.9"):
        try:
            with socket.create_connection((host, 53), timeout=2):
                return True
        except OSError:
            continue
    return False


def _sh(cmd, check=True):
    return subprocess.run(cmd, capture_output=True, text=True, check=check)


def apply_network(cfg: dict) -> list[str]:
    """Apply LAN address, forwarding, firewall and DHCP. Does not touch the WAN interface config."""
    net = cfg["network"]
    errs = validate_network(net)
    if not net.get("wan_iface") or not net.get("lan_iface"):
        errs.append("WAN/LAN interfaces are not configured.")
    if errs:
        return errs
    if cfg["simulation_mode"]:
        return []
    lan = net["lan_iface"]
    _sh(["ip", "link", "set", lan, "up"])
    _sh(["ip", "addr", "flush", "dev", lan])
    _sh(["ip", "addr", "add", f"{net['lan_ip']}/{net['lan_prefix']}", "dev", lan])
    Path("/proc/sys/net/ipv4/ip_forward").write_text("1\n")
    NFT_FILE.parent.mkdir(parents=True, exist_ok=True)
    NFT_FILE.write_text(render_nft(net))
    r = _sh(["nft", "-c", "-f", str(NFT_FILE)], check=False)  # syntax check before loading
    if r.returncode != 0:
        return ["nftables ruleset rejected: " + r.stderr.strip()]
    _sh(["nft", "-f", str(NFT_FILE)])
    DNSMASQ_CONF.write_text(render_dnsmasq(net))
    _sh(["systemctl", "restart", "dnsmasq"])
    return []


def firewall_restore():
    """Remove only our table: the machine falls back to its previous/default firewall behaviour."""
    subprocess.run(["nft", "delete", "table", "inet", TABLE], capture_output=True)


def firewall_status() -> dict:
    r = subprocess.run(["nft", "list", "table", "inet", TABLE], capture_output=True, text=True)
    return {"loaded": r.returncode == 0, "ruleset": r.stdout if r.returncode == 0 else r.stderr.strip()}


# ---------- effective (DB-overridable) network settings with rollback ----------
def effective_network(conn, cfg) -> dict:
    from .database import get_setting
    net = dict(cfg["network"])
    raw = get_setting(conn, "network_override", "")
    if raw:
        try:
            net.update(json.loads(raw))
        except ValueError:
            pass
    return net


EDITABLE_NET_KEYS = ("lan_ip", "lan_prefix", "dhcp_start", "dhcp_end", "dhcp_lease", "dns_servers")


def stage_network_change(conn, cfg, changes: dict, now: int) -> list[str]:
    """Validate, store the previous settings and arm the rollback timer. The monitor applies it;
    if nobody confirms in time (e.g. the admin lost access), it reverts automatically."""
    from .database import set_setting, tx
    net = effective_network(conn, cfg)
    previous = {k: net[k] for k in EDITABLE_NET_KEYS}
    candidate = dict(net)
    candidate.update({k: v for k, v in changes.items() if k in EDITABLE_NET_KEYS})
    errs = validate_network(candidate)
    if errs:
        return errs
    with tx(conn):
        set_setting(conn, "network_pending", json.dumps(
            {"previous": previous, "deadline": now + int(cfg["network"].get("confirm_seconds", 120))}))
        set_setting(conn, "network_override", json.dumps({k: candidate[k] for k in EDITABLE_NET_KEYS}))
        set_setting(conn, "network_apply_requested", "1")
    return []


def confirm_network_change(conn):
    from .database import set_setting
    set_setting(conn, "network_pending", "")


def rollback_due(conn, now: int) -> dict | None:
    from .database import get_setting
    raw = get_setting(conn, "network_pending", "")
    if not raw:
        return None
    try:
        p = json.loads(raw)
    except ValueError:
        return None
    return p if now > int(p.get("deadline", 0)) else None
